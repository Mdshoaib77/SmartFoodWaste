package com.foodwaste.tests;

import com.foodwaste.service.ServiceException;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/** Tiny test framework (no external libraries): records Test area | Test case | Expected | Actual | Pass/Fail. */
final class T {
    interface Action { void run() throws Exception; }

    static final class Result {
        final String area, name, expected, actual;
        final boolean pass;
        Result(String area, String name, String expected, String actual, boolean pass) {
            this.area = area; this.name = name; this.expected = expected; this.actual = actual; this.pass = pass;
        }
    }

    static final List<Result> RESULTS = new ArrayList<>();
    private static String area = "";

    private T() { }

    static void area(String a) {
        area = a;
        System.out.println("\n== " + a);
    }

    static void check(String name, String expected, String actual, boolean pass) {
        RESULTS.add(new Result(area, name, expected, actual, pass));
        System.out.println((pass ? "  PASS  " : "  FAIL  ") + name + (pass ? "" : "   expected: " + expected + "   actual: " + actual));
    }

    static void eq(String name, Object expected, Object actual) {
        boolean ok = expected == null ? actual == null : expected.toString().equals(String.valueOf(actual));
        check(name, String.valueOf(expected), String.valueOf(actual), ok);
    }

    static void yes(String name, String expected, boolean cond) {
        check(name, expected, cond ? expected : "condition was false", cond);
    }

    /** Passes when the action throws a ServiceException whose message contains the fragment (case-insensitive). */
    static void denied(String name, String fragment, Action a) {
        String expected = "ServiceException containing '" + fragment + "'";
        try {
            a.run();
            check(name, expected, "no exception (action succeeded)", false);
        } catch (ServiceException e) {
            String m = e.getMessage() == null ? "" : e.getMessage();
            check(name, expected, "ServiceException: " + m, m.toLowerCase(Locale.ROOT).contains(fragment.toLowerCase(Locale.ROOT)));
        } catch (Exception e) {
            check(name, expected, "unexpected " + e, false);
        }
    }

    /** Passes when the action finishes without any exception. */
    static void works(String name, String expected, Action a) {
        try {
            a.run();
            check(name, expected, "completed without error", true);
        } catch (Exception e) {
            check(name, expected, "exception: " + e, false);
        }
    }

    static int failures() {
        int n = 0;
        for (Result r : RESULTS) if (!r.pass) n++;
        return n;
    }

    private static String cell(String s) {
        String v = s == null ? "" : s.replace("|", "\\|").replace("\r", " ").replace("\n", " ");
        return v.length() > 220 ? v.substring(0, 217) + "..." : v;
    }

    static void writeReport(String path, String environment) throws IOException {
        StringBuilder sb = new StringBuilder();
        sb.append("# TEST REPORT\n\n");
        sb.append("This file is generated by `run-tests` (tests/com/foodwaste/tests/TestRunner.java) - every row below is a real result of the run.\n\n");
        sb.append(environment).append("\n");
        int pass = RESULTS.size() - failures();
        sb.append("**Total: ").append(RESULTS.size()).append(" | Passed: ").append(pass).append(" | Failed: ").append(failures()).append("**\n\n");
        sb.append("| Test area | Test case | Expected | Actual | Pass/Fail |\n|---|---|---|---|---|\n");
        for (Result r : RESULTS)
            sb.append("| ").append(cell(r.area)).append(" | ").append(cell(r.name)).append(" | ").append(cell(r.expected)).append(" | ")
              .append(cell(r.actual)).append(" | ").append(r.pass ? "PASS" : "**FAIL**").append(" |\n");
        Files.write(Paths.get(path), sb.toString().getBytes(StandardCharsets.UTF_8));
    }
}
